"""
schemas/chat.py
----------------
Schemas for the AI Chat (/api/chat) and Symptom Checker (/api/symptoms/check)
features.
"""

from datetime import datetime
from typing import List, Optional
from pydantic import BaseModel, Field, ConfigDict


# ---------- Chat ----------

class ChatRequest(BaseModel):
    message: str = Field(..., min_length=1, max_length=1000,
                          examples=["I have a headache and mild fever."])


class ChatResponse(BaseModel):
    ai_response: str
    is_emergency: bool
    disclaimer: str = (
        "This AI Health Assistant provides general health information and "
        "is not a substitute for professional medical advice."
    )


class ChatMessageOut(BaseModel):
    id: int
    user_message: str
    ai_response: str
    is_emergency: bool
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


# ---------- Symptom Checker ----------

class SymptomCheckRequest(BaseModel):
    symptoms: List[str] = Field(..., min_length=1, examples=[["headache", "fever", "fatigue"]])


class SymptomCheckResponse(BaseModel):
    symptoms: List[str]
    possible_explanations: str
    severity: str  # LOW / MODERATE / HIGH
    advice: str
    professional_attention_recommended: bool
    is_emergency: bool
    emergency_message: Optional[str] = None
    disclaimer: str = (
        "This result is general health information generated by an AI "
        "assistant. It is not a medical diagnosis."
    )


class SymptomCheckOut(BaseModel):
    id: int
    symptoms: str
    severity: Optional[str] = None
    possible_explanations: Optional[str] = None
    advice: Optional[str] = None
    is_emergency: bool
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)
